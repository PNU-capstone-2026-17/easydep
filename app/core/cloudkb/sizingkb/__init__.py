"""sizingkb: **요구사항을 자원 규모로 옮기는 규칙** — 좁게, 그리고 정직하게.

지식 차원 분담:

- `graphkb`    — 타입 간 의존성          - `costkb` — 스펙·가격
- `capacitykb` — 용량·제약               - `perfkb` — 성능
- `bundlekb`   — 하나를 고르면 뭐가 따라오나
- `sizingkb`   — 이 패키지 (**얼마나 크게 잡아야 하나**)

## 이 KB는 다른 넷과 성격이 다르다

앞의 넷은 **공개 스키마에 사실이 있다.** 사이징은 다르다 — "동시 사용자 1000명이면
vCPU 2"는 워크로드 성격(요청당 CPU 시간, 캐시 히트율, 런타임)에 따라 **10배 넘게**
갈린다. 그런 "정답"을 담는 KB를 만들면 **그게 바로 환각을 권위 있게 포장하는 것**이다.

`kb-roadmap.md` §7이 조사 전에 이미 그렇게 판단했고, 조사 결과도 같았다
(`document/archive/bundle-sizing-research-2026-07-22.md`).

## 그래서 담는 것은 넷뿐이다

전부 **원본이 공식으로 적어 둔 변환 규칙**이다.

    reserved_ips     서브넷 예약 IP 수 → 가용 IP = 2^(32−prefix) − 예약
    minimum          "K8s 노드는 vCPU 2 이상" 같은 하한
    required_count   "AWS EKS는 서브넷 2개가 필요" 같은 개수 요구
    reference_point  "웹서버 예시는 t3.small" — **정답이 아니라 참조점**
    preset           컨테이너 규모 프리셋(nano~2xlarge)

## 담지 않는 것

- **"동시 사용자 N명 → vCPU M"** 형태의 어떤 것도. 소스가 없다.
- 벤치마크 기반 성능 환산. SPEC에 인스턴스 타입이 0건이라 이미 재조사 금지 축이다.

## 원본이 단 경고는 값과 함께 담는다

bitnami 프리셋에는 원본 주석이 이렇게 붙어 있다 — *"These presets are for basic
testing and **not meant to be used in production**"*. 값만 옮기고 그 문장을 떼면
테스트용 숫자가 권장값으로 둔갑한다. `caveat`이 그래서 있다.

## 도구는 단정하지 않고 참조점을 준다

    ❌ "1000명이면 vCPU 2입니다"                      (근거 없는 단정)
    ✅ "/24 서브넷이면 AWS 기준 251대까지입니다"       (공식에서 계산)
    ✅ "이 소스의 웹서버 예시는 t3.small입니다"        (참조점)
    ✅ "사이징은 추정입니다. 부하 테스트로 검증하세요"  (정직)
"""
